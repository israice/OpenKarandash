// Общее определение языка для пары языковых хуков: language-reminder.js (до хода)
// и language-check.js (после). Раньше каждый считал сам и одинаково ошибался.
//
// Правило простое: язык определяется по письменности, а не по большинству букв.
// Заметная кириллица (или греческий, иврит, арабский, китайский, японский,
// корейский…) — значит, сообщение на этом языке, сколько бы латиницы рядом ни
// лежало. Причина: в обращение пользователя попадает служебный английский текст,
// которого он не писал — преамбула режима, карточка элемента интерфейса с
// текстом ошибки, цитата лога. По доле букв эта служебная масса перевешивала
// пару русских слов, и хуки объявляли русское сообщение английским.
//
// Латиница остаётся неоднозначной: по одной письменности английский от немецкого
// не отличить, поэтому для неё хук не называет язык, а велит смотреть на сам текст.

// письменность → как назвать язык в подсказке. Список закрытый: чего здесь нет,
// то считается неопознанным, и хук молчит, а не гадает
const SCRIPTS = [
    ['Cyrillic', 'русском'],
    ['Greek', 'греческом'],
    ['Hebrew', 'иврите'],
    ['Arabic', 'арабском'],
    ['Han', 'китайском'],
    ['Hiragana', 'японском'],
    ['Katakana', 'японском'],
    ['Hangul', 'корейском'],
    ['Devanagari', 'хинди'],
    ['Armenian', 'армянском'],
    ['Georgian', 'грузинском'],
    ['Thai', 'тайском'],
];

const MIN_LETTERS = 8;   // короче — судить не о чем
// «Заметно» — это одно слово, а не доля: короткое «зачем revoke ?» рядом с
// абзацем служебной английской преамбулы даёт полтора процента кириллицы, и
// любой порог по доле снова объявил бы его английским. Цена — англоязычное
// сообщение с одним русским словом внутри будет принято за русское; для этого
// проекта это лучше, чем регулярно отвечать не на том языке
const MIN_NON_LATIN = 4;

// код, инлайн-код, URL и пути файлов не обязаны совпадать по языку — вырезаем перед
// подсчётом, иначе имена функций/переменных в коде дают ложные срабатывания
function stripNonProse(text) {
    return text
        .replace(/```[\s\S]*?```/g, ' ') // код-блоки
        .replace(/`[^`\n]+`/g, ' ') // инлайн-код
        .replace(/https?:\/\/\S+/g, ' ') // URL
        .replace(/\]\([^)]*\)/g, ']') // URL/путь внутри markdown-ссылки, текст ссылки остаётся
        .replace(/(?:^|[\s(])(?:[A-Za-z]:)?(?:[\w.-]*[\\/])+[\w.-]+/g, ' '); // пути файлов (в т.ч. абсолютные /mnt/...)
}

// { script, name } для опознанной письменности, { script: 'Latin', name: null }
// для латиницы, null — если судить не о чем или письменности перемешаны поровну
function detect(text) {
    const stripped = stripNonProse(text);
    const latin = (stripped.match(/[A-Za-z]/g) || []).length;

    let best = null;
    let letters = latin;
    for (const [script, name] of SCRIPTS) {
        const count = (stripped.match(new RegExp(`\\p{Script=${script}}`, 'gu')) || []).length;
        if (!count) continue;
        letters += count;
        if (!best || count > best.count) best = { script, name, count };
    }

    if (letters < MIN_LETTERS) return null;
    if (best && best.count >= MIN_NON_LATIN) return { script: best.script, name: best.name };
    // чужой письменности нет или её след ничтожен — перед нами латиница
    if (latin / letters >= 0.9) return { script: 'Latin', name: null };
    return null; // ни то ни сё: лучше промолчать, чем назвать язык неверно
}

module.exports = { detect, stripNonProse };
