// Верхнее меню пульта, серверная половина: разметку верхнего ряда рисует сервер —
// шаблон topbar.eta лежит рядом (DOCS/decisions/005).
//
// Меню отдаётся в двух видах, и это не два источника, а один: подстановкой в
// страницу и тем же шаблоном маршрутом. Подстановка нужна потому, что верхний
// ряд держит на себе первую отрисовку (его высота заложена в тело каждой
// вкладки через --topbar-height) и его узлы нужны скриптам на старте — вкладкам,
// меню «+», кнопке «+», Karandash и Settings. Ждать отдельного запроса htmx
// после загрузки там нельзя: отложенные скрипты выполняются раньше него.
//
// Маршрут оставлен не для страницы, а для проверки и для будущей подмены: он
// отдаёт ровно то, что подставляется в страницу.

const { Eta } = require('eta');
const { sendHtml } = require('./core/http.js');

// свой экземпляр Eta со своей папкой шаблонов: так меню не зависит от того, где
// держит шаблоны сосед. cache:false — правка .eta видна без перезапуска сервера
const eta = new Eta({ views: __dirname, cache: false });

// вся статика меню; единственные данные в нём — подпись версии (it.version).
// Саму версию отсюда не читаем: модуль версии тянет этот файл (renderPage
// подставляет верхнее меню в страницу), и чтение оттуда замкнуло бы круг в
// графе модулей. Поэтому версию передают снаружи — и в страницу (renderPage),
// и в маршрут (createRoutes)
function render(data) {
    return eta.render('topbar', data);
}

function createRoutes({ currentVersion }) {
    return {
        '/api/fragment/topbar': (req, res) => {
            sendHtml(res, render({ version: currentVersion() }));
        },
    };
}

module.exports = { createRoutes, render };