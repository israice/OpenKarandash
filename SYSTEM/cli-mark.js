// Пометка пунктов списка CLI тем, что о них известно на этой машине.
//
// Отдельный файл от model-cascade.js: там сама строка выбора и правила её
// заполнения, здесь — один её вид. Каскаду о разведке знать нечего, и правка её
// вида не должна лезть в правила заполнения уровней.
//
// Пометка — атрибут data-mark, а не класс: у пункта уже есть класс служебной
// строки «Add», и общий вид пункктов задаёт правило в
// SYSTEM/styles/model-cascade.css. Правила с классами здесь нельзя было бы
// написать без войны за специфичность (общее правило для невыбранных пунктов
// сильнее любого класса на option'е), а с атрибутом метки просто разведены: общее
// правило на пункты без метки не действует вовсе.
//
// Три метки, и «неизвестно» от «нет» отличается намеренно — гасить пункт, о
// котором сервер не ответил, значит соврать человеку:
//
//   ready   команда есть и отвечает (зелёный фон)
//   empty   команда есть, но каталог моделей пуст (жёлтый фон)
//   missing команды на машине нет (гаснет до обычного серого)
//
// Метка, а не отключение: пункт остаётся выбираемым. Человек может прямо сейчас
// поставить этот CLI, и имя не должно исчезать у него из-под курсора.
const MARK_READY = 'ready';
const MARK_EMPTY = 'empty';
const MARK_MISSING = 'missing';

// Атрибут, а не класс: см. объяснение в шапке файла
const ATTR = 'data-mark';

export function markOption(option, mark) {
    if (mark) option.setAttribute(ATTR, mark);
    else option.removeAttribute(ATTR);
    return option;
}

// Пометка всего уровня. Пробегается по option'ам, а не по списку значений:
// уровень наполняется по-разному (у CLI имена из списка сайта, у Gateway — из
// каталога моделей), и переписывать наполнение ради пометки значило бы
// дублировать его. Уровень, который не про CLI (Gateway, Provider, Model,
// Effort), помечается вхолостую: там значения не имена CLI, и разведка про них
// ничего не знает
//
// Прежняя метка снимается всегда: разведка переопределяет метку (установленный
// CLI приходит «ready», а после connect с пустым каталогом становится «empty»),
// и без снятия прежняя осталась бы на пункте вторая
export function markCliLevel(select, markOf) {
    for (const option of select.options) markOption(option, markOf(option.value));
}

// Все уровни CLI, которые сейчас нарисованы, — чтобы перепометить их под новый
// ответ разведки. Хранится уровнями, а не строками: строка перерисовывается целиком
// и её select'ы меняются, а уровень остаётся тем же узлом, и подписка на
// разведку не должна была бы искать строку заново.
//
// Отсоединённые узлы выбрасываются сами: строка в шапке перерисовывается целиком
// (renderSessionBarControls чистит bar.innerHTML), и её уровень уходит из
// страницы навсегда. Отдельная отписка ради этого не нужна — от узла, которого
// в документе уже нет, переживать ответы незачем, а ждать его отписки пришлось бы
// вечно, потому что перерисовка не снимает слушателей сама
const levels = new Set();

export function watchCliLevel(select, markOf) {
    levels.add(select);
    markCliLevel(select, markOf);
}

// Разведка ответила — перепометить уровни, что на экране. Перерисовкой строки
// здесь обойтись нельзя: она сбросила бы уровень на прочерки у CLI, который ещё
// не подключён, и увела бы человека с выбранного пункта прямо в тот момент,
// когда он в него опустился
export function remarkCliLevels(markOf) {
    for (const select of [...levels]) {
        if (!select.isConnected) { levels.delete(select); continue; }
        markCliLevel(select, markOf);
    }
}

export { MARK_READY, MARK_EMPTY, MARK_MISSING };