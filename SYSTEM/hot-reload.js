// Горячая перезагрузка клиентских скриптов: переисполнить файл на месте.
//
// Живёт отдельно от app.js (DOCS/decisions/022, одна тема — один файл): ядро и
// так близко к четырёмстам строкам, а здесь четыре правила, которые к ядру
// отношения не имеют.
//
// Три вещи, о которых важно помнить, прежде чем править:
//
// 1. **Крючок `null` — не «рисовать нечего», а «рисовать нечего И перерисовать
//    нечего».** Такой скрипт только публикует функцию в window, и свежая копия
//    заменит её. Уже нарисованные экземпляры при этом остаются старыми: узел-то
//    построен прежним кодом. Если правка должна быть видна сразу, скрипт
//    регистрирует `redraw` (третьим элементом) — функцию, которая берёт уже
//    стоящий узел и строит такой же заново новым кодом.
//
// 2. **`dependent` — файл, который надо перерисовать, когда правят этот.** Нужен
//    поставщикам, которые рисует чужой скрипт: Settings собирает окно из пяти
//    файлов-поставщиков, и правка любого из них должна перерисовать окно целиком,
//    а не страницу. Поставщик сам не знает, кто его рисует, — знает settings.js.
//
// 3. **Проверка крючка синхронная.** Промис всегда истинный, поэтому «перерисовалось
//    ли» спрашивается до загрузки, а не после.
export function create(win) {
    // файл -> снять то, что он нарисовал (или null — рисовать нечего)
    const hotReloads = new Map();
    // файл -> перерисовать уже нарисованные им узлы
    const hotRedraws = new Map();
    // файл -> чью перерисовку вызвать, когда правят этот
    const dependents = new Map();

    // Порядок <script> в index.html не даёт гарантии: крючок регистрирует и файл,
    // который публикует функцию в window (SYSTEM/model-tag.js и подобные), и он
    // подключён раньше app.js — где win.App ещё undefined. Раньше вызов
    // `window.App?.registerHotReload` там просто ничего не делал, и правка такого
    // файла перезагружала страницу целиком. Поэтому крючки, пришедшие раньше ядра,
    // копятся в очереди на окне, а create() разбирает её после старта.
    const pending = win.__hotReloads || (win.__hotReloads = []);

    function register(file, cleanup, redraw, dependent) {
        hotReloads.set(file, cleanup);
        if (redraw) hotRedraws.set(file, redraw);
        if (dependent) dependents.set(file, dependent);
    }

    // Очередь разбираем лениво, перед любым ответом на вопрос про файл. Разбор один
    // раз при старте не годится: горячая перезагрузка поставщика исполняет его
    // заново, и он кладёт в очередь следующую запись — её уже никто не забирал,
    // и правка молча переставала работать. Плюс app.js подключён как type="module",
    // а модульные скрипты выполняются после всех defer, поэтому к моменту create()
    // в очереди лежит лишь часть крючков, а остальные приходят позже
    function drain() {
        if (!pending.length) return;
        for (const entry of pending.splice(0)) {
            if (!Array.isArray(entry)) continue;
            register(entry[0], entry[1], entry[2], entry[3]);
        }
    }

    // Спросить надо до загрузки: reloadScript возвращает промис, а промис всегда
    // истинный, и проверка его результата перезагрузила бы страницу по кругу.
    function canReloadScript(file) {
        drain();
        return hotReloads.has(file) && Boolean(win.document.querySelector(`script[data-hot-src="${file}"]`));
    }

    // Перерисовать узлы, нарисованные скриптом: скрипт отдаёт функцию, которая
    // берёт уже стоящий узел и строит такой же заново. Функции нет — рисующий
    // скрипт, и о нём подумал его же крючок hotReload: он снял старое и нарисовал
    // заново сам. Ошибку ловим: одна сломанная перерисовка не должна ронять
    // страницу, а страница без прежней правки — не молчание, а запись в консоль.
    function redraw(file, seen) {
        const fn = hotRedraws.get(file);
        if (fn) {
            try {
                fn();
            } catch (err) {
                console.error(`hot redraw ${file}:`, err);
            }
        }
        // поставщик: правят его — перерисовывает тот, кто его рисует
        const parent = dependents.get(file);
        if (parent && !seen.has(parent)) {
            seen.add(parent);
            refresh(parent, seen);
        }
    }

    // Перерисовать чужой раздел: снять его, переисполнить и нарисовать заново.
    // Это ровно то, что делает горячая перезагрузка, поэтому идёт тем же путём —
    // с защитой от петли (A тянет B, B тянет A), иначе правка одного файла
    // подвесила бы страницу.
    //
    // seen — файлы, уже начатые этой перерисовкой. Важно: свой собственный файл в
    // него НЕ кладём. Раньше тут стояло `new Set([file])`, и первая же строка
    // видела файл в множестве и уходила — reloadScript всегда отвечал false, то
    // есть не перерисовывал ничего, а правка файла молча ничего не делала
    async function refresh(file, seen = new Set()) {
        if (seen.has(file)) return false;
        seen.add(file);
        const cleanup = hotReloads.get(file);
        if (cleanup) {
            try {
                cleanup();
            } catch (err) {
                console.error(`hot reload ${file}:`, err);
                return false;
            }
        }
        const old = win.document.querySelector(`script[data-hot-src="${file}"]`);
        if (!old) return false; // поставщик перерисовывается, а сам не переисполняется

        const fresh = win.document.createElement('script');
        // те же атрибуты, что у исходного тега: обычный скрипт или ES-модуль
        for (const name of ['type', 'defer']) {
            if (old.hasAttribute(name)) fresh.setAttribute(name, old.getAttribute(name) || '');
        }
        fresh.dataset.hotSrc = file;
        fresh.src = `${file}?v=${Date.now()}`;
        const done = new Promise((resolve, reject) => {
            fresh.addEventListener('load', () => resolve());
            fresh.addEventListener('error', () => reject(new Error(`${file} не загрузился`)));
        });
        old.after(fresh);
        try {
            await done;
        } catch (err) {
            console.error(`hot reload ${file}:`, err);
            fresh.remove(); // сломанная копия в странице только мешает
            return false;
        }
        // старый тег своё дело сделал и больше не нужен: оставлять его — значит
        // копить по тегу на каждую правку файла. Заодно поиск по data-hot-src
        // после правки находит ровно один тег, а не последний из десятка
        old.remove();
        // свежая копия исполнилась и зарегистрировала свой крючок заново — теперь
        // перерисовываем то, что она нарисовала в прошлый раз. Порядок обязателен:
        // перерисовка зовёт функцию из window, а она принадлежит свежей копии
        redraw(file, seen);
        return true;
    }

    // Ни разбор один раз при старте, ни по готовности страницы не годится: горячая
    // перезагрузка поставщика исполняет его заново и кладёт следующую запись (её
    // уже никто не забирает), а app.js подключён как type="module", и модульные
    // скрипты выполняются после всех defer — к моменту create() в очереди лежит
    // лишь часть крючков. Поэтому очередь разбирается лениво, см. drain()
    return {
        register,
        registerHotReload: (file, rerender) => register(file, rerender),
        registerHotRedraw: (file, draw) => register(
            file, hotReloads.has(file) ? hotReloads.get(file) : null, draw
        ),
        // Поставщик объявляет, кто его рисует. Правка поставщика перерисовывает
        // раздел целиком, а сам поставщик (у него нет тега в странице) не
        // переисполняется: его функцию зовёт раздел, уже получивший свежую копию
        declareDependent: (file, parent) => { drain(); dependents.set(file, parent); },
        canReloadScript,
        reloadScript: (file) => {
            drain();
            // Поставщик: тега с его путём в странице нет, переисполнять нечего —
            // перерисовывается тот, кто его рисует, и зовёт уже его функцию.
            // Раньше здесь звался refresh(файл-поставщик), он искал несуществующий
            // тег и уходил с false: правка поставщика молча не делала ничего
            const parent = dependents.get(file);
            if (parent) return refresh(parent);
            // Крючок есть — снимаем своё и рисуем заново свежей копией
            if (canReloadScript(file)) return refresh(file);
            // ни крючка, ни поставщика: раздел за собой не умеет убираться, и
            // вторая копия легла бы поверх первой — тогда уж лучше перезагрузка
            return false;
        },
    };
}