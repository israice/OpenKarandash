// Что не обходят те, кто ходит по дереву проекта: сторож файлов в SYSTEM/core/watch.js и
// сборщик карты в PROJECTS/Graph/graph-vault.js. Список общий, потому что
// разъехавшиеся копии уже приводили к падению сторожа на чужом дереве.
// Папка данных добавляется каждым из них к себе: её имя берётся из DATA_DIR
// и не обязано совпадать с 'DATA'.

// logs/ — рантайм, worktrees — копии проекта у агентов: без этих исключений
// сборка карты при старте длится минуты и выглядит как зависание сервера
//
// .kilo — родительская папка копий (`.kilo/worktrees/<папка>`, ветки вида
// worktree-agent-<хеш>). Раньше копии не попадали в карту и сторож только потому,
// что папка внутри зовётся ровно `worktrees`, а этот список сравнивает по точному
// имени: dot-папки здесь никто отдельно не отсекает, и копия, положенная как
// `.kilo/<папка>`, уехала бы в карту целиком — со своим кодом, своими заметками и
// дублями версий. Имя папки — единственное, что держало обход в узде, поэтому
// оно и закреплено здесь явно. Тот же список у карты (graph-vault.js, MAP_SKIP)
// и у сторожа (watch.js, SKIP); у сторожа сверх того есть правило на всё,
// начинающееся с точки, но на карту оно не распространяется
const SKIP_NAMES = ['node_modules', '.git', '.kilo', 'DATA', 'logs', '.worktrees', 'worktrees'];

module.exports = { SKIP_NAMES };
