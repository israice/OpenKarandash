// Какое событие живой перезагрузки послать в браузер на правку файлов.
//
// Идея: точечное событие там, где граница компонента известна заранее и его можно
// перерисовать, не трогая остальную страницу. Полная перезагрузка — только там,
// где такой границы нет.
//
// Что уже умеет точечно:
//   *.eta                    → серверный фрагмент заново запрашивается по своему имени
//   *.css                    → у <link> меняется href, страница со всем состоянием остаётся
//   PROJECTS/<X>/page.js     → страница кнопки «+» собирается заново (SYSTEM/new-button.js)
//   PROJECTS/<X>/*.js        → скрипт раздела переисполняется и зовёт его hotReload
//   SYSTEM/*.js              → то же для общих скриптов
//
// Переисполнение скрипта само по себе мало: раздел навесил слушателей и нарисовал
// разметку при загрузке. Поэтому у скрипта должен быть зарегистрирован крючок
// hotReload — раздел сам говорит, что именно перерисовать (App.registerHotReload).
// Крючок `null` означает «я ничего не рисую, только публикую функции в window»:
// такой скрипт переисполняется, а страница не трогается вовсе — правка видна
// следующим нарисованным элементом. Нет крючка — перезагрузка страницы целиком:
// лишний раз перезагрузить дешевле, чем оставить страницу с наполовину
// перерисованным разделом.
//
// Вынесено из server.js отдельным модулем, чтобы правило было видно целиком и
// его можно было позвать напрямую, не поднимая сервера.
const path = require('path');

// клиентский JS, который можно перерисовать на месте: свой скрипт раздела или
// общий скрипт SYSTEM. Встроенный вендор (PROJECTS/Graph/vendor) — нет.
const CLIENT_SCRIPT = /^(PROJECTS\/(?!Graph\/vendor\/)[^/]+\/|SYSTEM\/)[^/]+\.js$/;

// Правки, которые страницу не трогают вообще: записки, решения, данные, служебные
// скрипты. Раньше любая из них доходила до правила в конце функции и отвечала
// полной перезагрузкой — то есть запись в записке гасила открытую страницу, и
// повторялось это каждые несколько минут работы агента над документацией.
// Для браузера такой файл неотличим от отсутствия правки: страница его не грузит.
// Карта проекта про такие файлы узнаёт отдельно, по составу папки (см. watch.js).
const NOT_FOR_PAGE = /\.(md|txt|yml|yaml|toml|sh|ps1|py|db|sqlite|lock|log)$/i;

function reloadEvents(root, files) {
    // Удалённый файл разбираем по тому же правилу, что и правый: путь-то известен.
    // Раньше удаление любого файла перезагружало страницу — включая удаление записки
    const events = new Set();
    for (const file of files || []) {
        const rel = path.relative(root, file).split(path.sep).join('/');

        if (NOT_FOR_PAGE.test(rel)) continue; // страницу это не касается

        // каркас страницы целиком: его <script> и <link> перечислены вручную, и
        // подмена одного из них невозможна — список надо читать заново
        if (rel === 'SYSTEM/index.html') { events.add('reload'); continue; }

        // шаблон фрагмента лежит в папке своей фичи (PROJECTS/Sessions/session-list.eta),
        // а зовётся по имени файла: оно же имя маршрута /api/fragment/<имя>
        const template = rel.match(/([^/]+)\.eta$/);
        if (template) { events.add(`fragment:${template[1]}`); continue; }

        // PROJECTS/<папка>/page.js — страница кнопки «+» целиком; у встроенных
        // разделов файла с таким именем нет, так что под правило попадают только они.
        // Её page.css ложится под общее правило *.css само собой
        const page = rel.match(/^PROJECTS\/([^/]+)\/page\.js$/);
        if (page) { events.add(`page:${page[1]}`); continue; }

        if (rel.endsWith('.css')) { events.add(`css:${rel}`); continue; }

        // клиентский скрипт раздела: сначала пробуем его hotReload, а нет крючка —
        // клиент сам откатится к полной перезагрузке
        if (CLIENT_SCRIPT.test(rel)) { events.add(`script:${rel}`); continue; }

        // серверный модуль: после правки перезапускается сервер, и страницу надо
        // взять заново. Всё остальное, чего страница не грузит (картинки, .json,
        // шрифты), сюда тоже попадает — но это молчаливая смена картинки без
        // перезагрузки, куда лучше лишней перезагрузки
        events.add('reload');
    }
    return [...events];
}

module.exports = { reloadEvents, NOT_FOR_PAGE };