// Тег модели над ответом — один источник разметки на три отображения
// (Sessions, Feed, Flow; DOCS/decisions/039). Ответ всегда подписан той
// моделью, которая его дала, а выбор модели в шапке сессии определяет, чем
// подпишется следующий ответ: без подписи не видно, где кончилась одна
// модель и началась другая (ход передают другому исполнителю, модель в том
// числе — DOCS/decisions/061, 066).
//
// Само поле model кладёт сервер в строку сообщения (колонка messages.model,
// см. SYSTEM/core/sessions-db.js), отсюда его и берут все три страницы; здесь
// только перевод его в человеческие слова и разметка плашки. Стиль —
// SYSTEM/model-tag.css, как у пометки суждения.
//
// Обычный скрипт, а не ES-модуль: flow.js подключён с defer и импортировать
// не может, поэтому общий механизм публикуется наружу через window — то же
// правило, что у MissionFiles, SidebarResize и TurnJudgment.

(() => {
    // «openrouter/stealth/space-bunny-alpha» и cli «pi» → «pi/openrouter/stealth/
    // space-bunny-alpha». Показывается весь путь к модели, каким он и приходит:
    // исполнитель, шлюз, поставщик, модель. Раньше в подписи оставался только
    // хвост («Space Bunny Alpha»), но по нему не видно было, через какой шлюз и
    // чей поставщик отвечал, а при передаче хода другому исполнителю путь
    // меняется целиком. Хвост после двоеточия (вариант «:free» у OpenRouter) и
    // подчёркивания — часть одной и той же строки, поэтому и они становятся
    // читаемыми, а не остаются в виде мусора
    function label(model, cli) {
        if (typeof model !== 'string') return '';
        const levels = [].concat(cli || [], model.trim().split('/'));
        return levels
            .map((level) => level.split(':')[0].replace(/_/g, '-'))
            .join('/');
    }

    // Плашка с названием модели. model неизвестен (старая строка, ход не от
    // браузера) — плашки нет вовсе: пустая подпись «неизвестно» была бы
    // шумом в каждой строке, а честно сказать тут нечего. cli — кто вёл ход:
    // у строки из базы он есть в её поле source, у идущего хода — выбор CLI в
    // шапке сессии (как у модели, getActiveModel в SYSTEM/model-cascade.js).
    function tag(model, cli) {
        const text = label(model, cli);
        if (!text) return null;
        const span = document.createElement('span');
        span.className = 'model-tag';
        span.textContent = text;
        // путь целиком — в подсказке: подпись обрезается по ширине пузыря
        // (SYSTEM/model-tag.css), и обрезанный конец виден только здесь.
        // Заодно она переживает горячую перерисовку: title сам себе полный
        // путь, поэтому плашку можно построить заново одним аргументом
        span.title = text;
        return span;
    }

    window.ModelTag = { label, tag };

    // Я только публикую функцию: свою разметку не рисую и слушателей не вешаю,
    // поэтому снимать здесь нечего. Правка файла переисполняет его целиком, а
    // страница со всем состоянием остаётся на месте.
    //
    // null — «рисовать нечего». Регистрация идёт через очередь на окне, а не через
    // window.App: этот файл подключён раньше app.js, и App там ещё нет.
    //
    // Третьим идёт перерисовка: плашка уже стоит на странице и держит полный путь
    // в title (с cli первым уровнем), поэтому её можно построить заново новым
    // кодом — на всех трёх отображениях сразу. Без неё правка была бы видна
    // только в следующей нарисованной плашке, а все уже нарисованные остались
    // бы старыми.
    (window.__hotReloads || (window.__hotReloads = [])).push([
        'SYSTEM/model-tag.js',
        null,
        () => {
            document.querySelectorAll('.model-tag').forEach((node) => {
                const fresh = window.ModelTag.tag(node.title);
                // подпись могла стать пустой (например, правило изменилось так, что
                // хвост имени больше не читается) — тогда плашки быть не должно
                if (fresh) node.replaceWith(fresh);
                else node.remove();
            });
        },
    ]);
})();
