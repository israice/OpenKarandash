// Флаг, которым CLI сам разрешает права в неинтерактивном ходе.
//
// Ход, который запускает пульт, всегда неинтерактивен: спрашивать права
// некому. CLI, у которого право по умолчанию «спросить», в таком ходе ничего не
// спросит — он молча откажет и продолжит. Так обрывалась работа на первом же
// шаге: чтение файла за пределами папки проекта уходило в «спросить человека»,
// ответа не было, инструмент возвращал отказ, а ход на этом нередко и
// заканчивался.
//
// Поэтому берём тот флаг, который для этого предназначен у самого CLI, и
// читаем его из его справки рядом с семейством протокола. Имена CLI не
// перечисляем: у kilo это `--auto` («auto-approve permissions that are not
// explicitly denied»), у следующего будет свой, и ход пойдёт тем же правилом.
// Права, которые CLI запрещает явно, остаются запрещёнными — флаг разрешает
// всё, что не запрещено. Строгие исключения проекта этому не противоречат
// (DOCS/decisions/044, 074): у исполнителя они и так полные, а вопросов к
// человеку в ходе нет by design.
//
// Отбираем строго, иначе подошла бы не та опция: строка справки обязана быть
// строкой опции, а её описание — говорить именно об одобрении прав. У pi
// неинтерактивность задаёт сам `-p`, и описание его ничего не говорит про
// права, — отсеивается правильно.
function headlessApproveFlag(help) {
    for (const line of String(help || '').split(/\r?\n/)) {
        if (!/^\s*(-|--)/.test(line)) continue;
        const flags = line.match(/--[a-z0-9][a-z0-9-]*/g) || [];
        if (!flags.length) continue;
        const description = line.slice(line.indexOf(flags[0]) + flags[0].length);
        if (!/approve/i.test(description)) continue;
        if (!/permission|not explicitly denied|everything/i.test(description)) continue;
        return flags[0];
    }
    return null;
}

module.exports = { headlessApproveFlag };