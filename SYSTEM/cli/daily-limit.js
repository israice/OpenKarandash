// Дневной лимит провайдера: узнаём по тексту ошибки, без суждения модели.
//
// Суждение о поломке хода (`SYSTEM/core/failure-judgment.js`) здесь не годится
// по простой причине: когда лимит исчерпан, модель больше не отвечает — то
// есть спросить её нечем. Плюс оно отвечает на другой вопрос («почему сломался
// ход»), а человеку здесь нужно другое: «на сегодня всё израсходовано» и
// «продолжи сам, сменив источник».
//
// Узнавание по тексту, а не по имени провайдера: одна и та же строка приходит и
// от openrouter, и от любого его шлюза, а название шлюза в сообщении может и не
// быть.
const DAILY_LIMIT = [
    /rate limit/i,
    /rate_limit/i,
    /too many requests/i,
    /\b429\b/,
    /daily\s+(?:limit|quota)/i,
    /usage\s+limit/i,
    /hit your .{0,30}limit/i,
    /(?:limit|quota|credits|balance)[^.\n]{0,40}(?:exhausted|exceeded|reached|depleted|used up)/i,
    /exceeded your current quota/i,
    /insufficient (?:credits|quota|balance)/i,
    /free-models-per-day/i,
];

// Повод, по которому ход останавливают досрочно и зовут человека. Словами
// человека, а не текстом провайдера: сырое сообщение об ошибке идёт следом
// отдельной строкой (finishExchange пишет его как строку ответа с
// stopReason='error'), поэтому в этом тексте — только что делать дальше.
const LIMIT_NOTICE = 'Дневной лимит модели на сегодня исчерпан. Продолжить работу можно с другой моделью или другим CLI: смените выбор в строке над сессией и нажмите «Продолжить».';

// Тот же смысл при другой причине: лимит тут ни при чём, а предел продолжений
// исчерпан — работа зациклилась и продолжать вслепую опасно.
const BOUND_NOTICE = 'Ход не доведён до ответа за {n} продолжений — работа остановлена. Нажмите «Продолжить», чтобы вернуться к ней.';

// Продолжать нечем: CLI не назвал свою сессию, а без неё вернуться к работе
// нельзя — следующий запуск начался бы с нуля и повторил бы сделанное.
const NO_RESUME_NOTICE = 'Ход не доведён до ответа, и CLI не дал своей сессии, чтобы вернуться к ней. Нажмите «Продолжить», чтобы начать заново.';

function isDailyLimit(text) {
    const value = String(text || '');
    return DAILY_LIMIT.some((pattern) => pattern.test(value));
}

module.exports = { isDailyLimit, LIMIT_NOTICE, BOUND_NOTICE, NO_RESUME_NOTICE };