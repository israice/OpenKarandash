// «UI element: «New» button#newButton.icon-button.btn-group__btn — section …»
// → ['newButton', 'icon-button', 'btn-group__btn']
//
// Строка «section chatView» в том же описании — не якорь, а место: такой id
// есть в десятке файлов (вкладка вставляется в разметку откуда-то), и поиск по
// нему уводит в сторону. Поэтому слова после «section» отбрасываем, а остальные
// якоря ранжирует collect.js по числу попаданий: чем их меньше, тем якорь
// точнее.
// Якоря берём из двух разных мест, и это важно: «section chatView» в описании
// элемента — не якорь, а место, и `chatView` нашёлся бы как camelCase-имя, да
// ещё в десятке файлов. Поэтому строку «section …» отбрасываем, а classNames и
// camelCase ищем только в комментарии — там имени принадлежит всё.
function codeAnchors(message) {
    const found = new Set();
    const elementLine = (message.match(/UI element:[^\n]*/i) || [''])[0]
        .replace(/[—-]\s*section\b.*$/i, '');
    for (const m of elementLine.matchAll(/[#.]([A-Za-z][\w-]*)/g)) found.add(m[1]);

    const comment = (message.match(/Comment:\s*([\s\S]*)/i) || [, message])[1];
    for (const m of comment.matchAll(/\b([a-z][a-z0-9]+(?:[A-Z][a-z0-9]+)+)\b/g)) found.add(m[1]);

    // Заглавное слово среди обычных — почти всегда имя в коде (Home, OpenCode,
    // Telegram), а не первая буква фразы. В прозе без «UI element» это
    // единственный точный якорь: задача «сперва Home, потом та страница» про
    // восстановление вкладки без него не находилась вообще
    const first = new Set(['Комментарий', 'Comment', 'Сделай', 'Добавь', 'Исправь', 'Надо', 'Нужно', 'Помоги']);
    for (const w of comment.split(/\s+/)) {
        const clean = w.replace(/^[«"'(]|[»"').,!:;?]+$/g, '');
        if (clean.length < 3 || !/^[A-Z][A-Za-z0-9]+$/.test(clean)) continue;
        if (first.has(clean)) continue;
        found.add(clean);
    }
    return [...found].slice(0, 8);
}

// имена в «ёлочках» и сочетания из слов комментария.
//
// Сочетания берём не с начала: там служебные слова («помоги исправить сейчас
// появляется…»), и индекс находит по ним сами себя — прошлую сессию с тем же
// текстом, а не код. Берём середину и конец фразы, где стоит сама просьба, и
// пропускаем сочетание, если оно уже начинается с найденного «ёлочками».
function phrases(message) {
    const out = [];
    const named = [];
    for (const m of message.matchAll(/«([^»]{2,40})»/g)) named.push(m[1]);
    out.push(...named);
    const comment = (message.match(/Comment:\s*([\s\S]*)/i) || [, message])[1];
    const words = (comment.toLowerCase().match(/[a-zа-яё][a-zа-яё0-9-]{2,}/g) || [])
        .filter((w) => !STOP.has(w));
    const uniq = [...new Set(words)];
    const windows = [];
    for (const at of [2, Math.floor(uniq.length / 2), uniq.length - 3]) {
        if (at < 0 || at + 3 > uniq.length) continue;
        const phrase = uniq.slice(at, at + 3).join(' ');
        if (!windows.includes(phrase)) windows.push(phrase);
    }
    for (const w of windows) {
        // сочетание, целиком состоящее из уже названного имени, индексу ничего
        // не добавит — второй раз тот же запрос только тратит время
        if (!named.some((n) => n.toLowerCase().includes(w))) out.push(w);
    }
    return [...new Set(out)].slice(0, 4);
}

// Слово комментария считаем попаданием по слову-основе, а не по подстроке:
// иначе «прав» (выравнивание по правому краю) матчится внутри «по-ЯВ-ляется».
// Совпадение — общее начало слова и ключа: «обновлени» ~ «обновление».
// Сильное слово (с `*`) перевешивает несколько обычных: «обновление страницы» —
// это про восстановление вкладки, а не про создание страницы, хотя слова
// «страниц» в ней больше.
function matches(word, key) {
    const n = Math.min(word.length, key.length);
    return n >= 3 && word.slice(0, n) === key.slice(0, n);
}

function kindOf(message) {
    const words = (message.toLowerCase().match(/[a-zа-яё][a-zа-яё0-9-]{1,}/g) || []);
    let best = null;
    let bestScore = 0;
    for (const kind of KINDS) {
        let score = 0;
        for (const word of words) {
            for (const key of kind.words) {
                if (key.endsWith('*') && matches(word, key.slice(0, -1))) { score += 3; break; }
                if (!key.endsWith('*') && matches(word, key)) { score += 1; break; }
            }
        }
        if (score > bestScore) { best = kind; bestScore = score; }
    }
    return bestScore > 0 ? best : null;
}

// Место элемента в коде из строки «Code: SYSTEM/model-tag.js:39 (здесь создаётся),
// SYSTEM/model-tag.css:6 (стиль)» — её добавляет Karandash, когда человек кликнул
// по элементу (DOCS/decisions/091). Это готовая находка: файл и строки уже названы,
// осталось их прочитать. Раньше та же работа делалась поиском по имени класса,
// а имя класса у общего элемента уводило не туда
const CODE_LINE = /Code:\s*([\s\S]*)/i;

function placesOf(message) {
    // без строки «Code:» в сообщении совпадения нет, и [''][1] — это undefined:
    // падение случалось на любом поручении словами, где нет клика по элементу
    const line = (String(message).match(CODE_LINE)?.[1] || '').split('\n')[0];
    const out = [];
    for (const m of line.matchAll(/([\w./-]+\.(?:js|mjs|cjs|html|eta|css)):(\d+)/g)) {
        const file = m[1].replace(/^\.\//, '');
        // стиль помечаем по самому файлу: слово «стиль» стоит в конце группы и
        // ко всем её местам не относится
        if (!out.some((p) => p.file === file)) out.push({ file, lines: [Number(m[2])], style: file.endsWith('.css') });
    }
    return out.slice(0, 3);
}

function anchorsOf(message) {
    return { code: codeAnchors(message), phrases: phrases(message), kind: kindOf(message), places: placesOf(message) };
}

// Правила типа задачи целиком не берём: они и так есть у агента на диске, а в
// отчёте нужен указанием на файл и строки, где тип задачи описан. Иначе отчёт
// раздуется и съест ровно тот выигрыш, ради которого делается.
function rulesOf(kindId) {
    const kind = KINDS.find((k) => k.id === kindId);
    if (!kind) return null;
    const rel = `DOCS/agents/${kind.rules}`;
    const rules = { id: kind.id, file: rel, check: kind.check, lines: 0 };
    try {
        rules.lines = fs.readFileSync(path.join(ROOT, rel), 'utf8').split('\n').length;
    } catch { /* файла нет — отчёт просто без указания */ }
    return rules;
}

