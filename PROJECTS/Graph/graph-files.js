// Вкладка Graph, файл из узла графа: чтение и запись по пути, который прислал
// клиент. Это граница доверия — путь проверяется так же, как при раздаче статики,
// и наружу корня проекта не выпускается. Корень, папка vault и список текстовых
// расширений общие с картой — берутся из graph-vault.js.

const fs = require('fs');
const path = require('path');
const { ROOT, VAULT_DIR, TEXT_FILES } = require('./graph-vault.js');

// ---------- чтение и правка файла из графа ----------

// узел графа открывается в окне с содержимым, поэтому нужен доступ к самому файлу.
// путь приходит от клиента — проверяем его так же, как при раздаче статики
const MAX_EDIT_BYTES = 2 * 1024 * 1024; // больше в textarea всё равно не отредактировать

// сравнивать надо реальные пути: символическая ссылка внутри проекта указывала бы
// наружу, а обычная склейка строк этого не заметила бы
const ROOT_REAL = fs.realpathSync(ROOT);

function resolveInsideRoot(relative) {
    const candidate = path.resolve(ROOT_REAL, String(relative || ''));
    let real;
    try {
        real = fs.realpathSync(candidate);
    } catch {
        // файла может не быть — тогда проверяем папку, в которой он должен лежать
        try {
            real = path.join(fs.realpathSync(path.dirname(candidate)), path.basename(candidate));
        } catch {
            return null;
        }
    }
    return real === ROOT_REAL || real.startsWith(ROOT_REAL + path.sep) ? real : null;
}

function readProjectFile(relative) {
    const full = resolveInsideRoot(relative);
    if (!full) return { ok: false, error: 'Path outside the project' };

    let stat;
    try {
        stat = fs.statSync(full);
    } catch {
        return { ok: false, error: `File not found: ${relative}` };
    }
    if (stat.isDirectory()) return { ok: false, error: 'This is a folder, not a file' };

    const rel = path.relative(ROOT_REAL, full).split(path.sep).join('/');
    if (!TEXT_FILES.test(rel)) {
        return { ok: true, path: rel, binary: true, size: stat.size, editable: false };
    }
    if (stat.size > MAX_EDIT_BYTES) {
        return { ok: true, path: rel, binary: true, size: stat.size, editable: false, note: 'File is too large to edit' };
    }

    // заметки vault генерируются заново при каждой пересборке: править их бессмысленно,
    // правка исчезнет через несколько секунд
    const generated = rel.startsWith(`${VAULT_DIR}/`);
    return {
        ok: true,
        path: rel,
        text: fs.readFileSync(full, 'utf8'),
        size: stat.size,
        editable: !generated,
        note: generated ? 'This note is generated by the server — edits will be overwritten on the next rebuild' : undefined,
    };
}

function writeProjectFile(relative, text) {
    const full = resolveInsideRoot(relative);
    if (!full) return { ok: false, error: 'Path outside the project' };

    const rel = path.relative(ROOT_REAL, full).split(path.sep).join('/');
    if (rel.startsWith(`${VAULT_DIR}/`)) return { ok: false, error: 'Vault notes are rebuilt automatically' };
    if (!TEXT_FILES.test(rel)) return { ok: false, error: 'Binary files cannot be edited' };
    if (!fs.existsSync(full)) return { ok: false, error: `File not found: ${rel}` };
    if (typeof text !== 'string') return { ok: false, error: 'No text to write' };

    try {
        fs.writeFileSync(full, text);
    } catch (error) {
        return { ok: false, error: `Failed to write the file: ${error.message}` };
    }
    return { ok: true, path: rel, size: Buffer.byteLength(text) };
}

module.exports = {
    MAX_EDIT_BYTES, // маршрут /api/file/write во входе поднимает по нему лимит readJson
    readProjectFile,
    writeProjectFile,
};
